def emit_qm31_tower():
    hdr = read_text(QM31_GEAR)

    def header_line(marker):
        for line in hdr.split("\n"):
            if marker in line:
                assert line.startswith(";;"), line
                # normalize whitespace; drop the gear comment tail after
                # the double-hyphen separator (the spec bans dash prose)
                return " ".join(line[2:].split()).split(" -- ")[0].strip()
        raise AssertionError("qm31.clar header drifted: " + marker)

    return "\n".join([
        src_note("contracts/full/qm31.clar (header: tower polynomials"
                 " and element shape)"),
        "",
        "```text",
        header_line("CM31 = M31[i]"),
        header_line("QM31 = CM31[u]"),
        header_line("An element {c0,c1,c2,c3} means"),
        "```",
    ])



def read_text(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def contract_slice(text, start_anchor, end_anchor):
    """Lines from the unique line containing start_anchor up to but not
    including the first later line containing end_anchor. Asserts the
    start anchor is unique so silent drift is impossible."""
    lines = text.split("\n")
    starts = [i for i, l in enumerate(lines) if start_anchor in l]
    assert len(starts) == 1, (start_anchor, len(starts))
    ends = [i for i, l in enumerate(lines)
            if end_anchor in l and i > starts[0]]
    assert ends, end_anchor
    return "\n".join(lines[starts[0]:ends[0]]).rstrip()


def src_note(*sources):
    return ("<!-- generated by tools/gen_spec_tables.py from: "
            + "; ".join(sources) + " -->")



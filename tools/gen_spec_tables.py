"""gen_spec_tables.py: owns every generated block of docs/protocol-spec.md.

Splices deterministic content between HTML-comment fences:
    <!-- BEGIN-GENERATED: <block-id> -->
    <!-- END-GENERATED: <block-id> -->
Refuses to run when any BEGIN lacks its END, an id is unknown, or an id
repeats, listing every offender. Each block's content is read from a
named source (tools/params.py, tools/soundness.py, the production
contracts, tools/kats-full.json, docs/m3-testnet-receipts.md); this file
inlines no protocol value. Deterministic: no timestamps, no env reads.
Run:   python3 tools/gen_spec_tables.py     (regenerates the spec in place)
Tests: python3 tools/test_gen_spec_tables.py
"""

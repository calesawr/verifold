# ---------------- fence engine ----------------

def parse_fences(text):
    """Returns (lines, [(block_id, begin_idx, end_idx)]). Collects every
    violation before failing so one run reports all offenders."""
    lines = text.split("\n")
    fences, errors, seen = [], [], set()
    open_id, open_at = None, None
    for i, line in enumerate(lines):
        stripped = line.strip()
        m = FENCE_RE.match(stripped)
        if not m:
            if stripped.startswith("<!-- BEGIN-GENERATED") or \
                    stripped.startswith("<!-- END-GENERATED"):
                errors.append("line {}: malformed fence: {}".format(
                    i + 1, stripped))
            continue
        kind, bid = m.group(1), m.group(2)
        if kind == "BEGIN":
            if open_id is not None:
                errors.append("line {}: BEGIN {} inside open block {}"
                              .format(i + 1, bid, open_id))
            if bid in seen:
                errors.append("line {}: duplicate block id {}".format(
                    i + 1, bid))
            if bid not in EMITTERS and bid not in PENDING:
                errors.append("line {}: unknown block id {}".format(
                    i + 1, bid))
            open_id, open_at = bid, i
            seen.add(bid)
        else:
            if open_id is None:
                errors.append("line {}: END {} without BEGIN".format(
                    i + 1, bid))
            elif bid != open_id:
                errors.append("line {}: END {} does not match BEGIN {}"
                              .format(i + 1, bid, open_id))
                open_id, open_at = None, None
            else:
                fences.append((bid, open_at, i))
                open_id, open_at = None, None
    if open_id is not None:
        errors.append("BEGIN {} never closed".format(open_id))
    if errors:
        raise FenceError("fence validation failed:\n  "
                         + "\n  ".join(errors))
    return lines, fences


def splice(text):
    lines, fences = parse_fences(text)
    out, cursor = [], 0
    for bid, b, e in fences:
        out.extend(lines[cursor:b + 1])
        out.append(render(bid))
        cursor = e
    out.extend(lines[cursor:])
    return "\n".join(out), len(fences)


def main():
    text = read_text(SPEC)
    new, n = splice(text)
    if new != text:
        with open(SPEC, "w", encoding="utf-8") as f:
            f.write(new)
    print("gen_spec_tables: {} blocks regenerated".format(n))


if __name__ == "__main__":
    main()

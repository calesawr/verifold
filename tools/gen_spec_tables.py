def emit_transcript_schedule():
    import json
    flat = read_text(FLAT)
    n = int(re.search(r"\(define-constant schedule/N u(\d+)\)",
                      flat).group(1))
    l = int(re.search(r"\(define-constant schedule/L u(\d+)\)",
                      flat).group(1))
    dom = int(re.search(r"\(define-constant schedule/DOMAIN_SIZE u(\d+)\)",
                        flat).group(1))
    code = contract_slice(flat,
                          "(define-read-only (schedule/derive-challenges",
                          "(define-read-only (schedule/get-params")
    # cross-check the schedule shape against the committed KAT export
    with open(os.path.join(HERE, "kats-full.json")) as f:
        kats = json.load(f)
    assert len(kats["friRoots"]) == l and len(kats["betas"]) == l
    assert len(kats["queryIndices"]) == n
    for key in ("ctx", "traceRoot", "compRoot", "alpha", "zfelt", "Tz",
                "Tgz", "Tg2z", "Czs", "gamma", "final", "nonce"):
        assert key in kats, key
    steps = [
        "init: state = sha256(ctx)",
        "absorb T_ROOT trace root, then squeeze one QM31: alpha",
        "absorb T_ROOT composition root, then squeeze one QM31: z",
        "absorb T_QM31 seven times, in order t(z), t(gz), t(g^2 z),"
        " c0(z), c1(z), c2(z), c3(z), with no squeeze between them",
        "squeeze one QM31: gamma",
        "for each of the {} FRI roots in layer order: absorb T_ROOT the"
        " root, then squeeze one QM31: beta of that layer".format(l),
        "absorb T_QM31 the transmitted final value",
        "proof of work check on the current state with the 8 byte nonce"
        " (reads the state, does not advance it)",
        "absorb T_NONCE the nonce",
        "squeeze m31 {} times; each query index is the squeezed value"
        " mod {}".format(n, dom),
    ]
    out = [src_note("contracts/verifold-flat-full-production.clar"
                    " (schedule gear: constants and derive-challenges);"
                    " cross-checked against tools/kats-full.json"), "",
           "| step | operation |", "| --- | --- |"]
    out += ["| {} | {} |".format(i + 1, s) for i, s in enumerate(steps)]
    out += ["", "The normative definition, verbatim:", "",
            "```clarity", code, "```"]
    return "\n".join(out)


def emit_air_constants():
    d = params.derived(params.PRODUCTION_POINT)
    flat = read_text(FLAT)
    cair = {}
    for name in ("SX", "SY", "SEL_A", "SEL_B", "SEL_C",
                 "B01_A", "B01_B", "B01_C"):
        m = re.search(r"\(define-constant cair/" + name + r" u(\d+)\)",
                      flat)
        assert m, name
        cair[name] = int(m.group(1))
    # the contract constants must equal the math recomputed by params.py
    assert (cair["SX"], cair["SY"]) == (d["SX"], d["SY"])
    assert (cair["SEL_A"], cair["SEL_B"], cair["SEL_C"]) == \
        (d["SEL"]["A"], d["SEL"]["B"], d["SEL"]["C"])
    assert (cair["B01_A"], cair["B01_B"], cair["B01_C"]) == \
        (d["B01"]["A"], d["B01"]["B"], d["B01"]["C"])
    # air_id registry rows from params.POINTS (id -> point names)
    by_id = {}
    for name in sorted(params.POINTS):
        by_id.setdefault(params.POINTS[name]["air_id"], []).append(name)
    # the registry rule, quoted from the params.py source comment
    psrc = read_text(os.path.join(HERE, "params.py"))
    rule = [" ".join(l[1:].split()) for l in psrc.split("\n")
            if l.startswith("#") and ("air_id registry is monotonic" in l
                                      or "production-trace circle" in l
                                      or "never reuse a retired id" in l)]
    assert rule, "params.py registry comment drifted"
    out = [src_note("tools/params.py (derived() SEL/B01, POINTS, the"
                    " registry comment); cross-checked against the cair"
                    " constants in contracts/"
                    "verifold-flat-full-production.clar"), "",
           "Selector and boundary lines (A*x + B*y + C, M31"
           " coefficients), equal in params.py and the contract:", "",
           "| line | A | B | C | vanishes on |", "| --- | --- | --- |"
           " --- | --- |",
           "| SEL | {A} | {B} | {C} | the last two trace coset points |"
           .format(**d["SEL"]),
           "| B01 | {A} | {B} | {C} | the first two trace coset points |"
           .format(**d["B01"]),
           "", "Trace step (S = generator of the trace coset walk):", "",
           "| constant | value |", "| --- | --- |",
           "| SX | {} |".format(d["SX"]),
           "| SY | {} |".format(d["SY"]),
           "", "air_id registry (from params.POINTS):", "",
           "| air_id | parameter points carrying it |", "| --- | --- |"]
    out += ["| {} | {} |".format(k, ", ".join(v))
            for k, v in sorted(by_id.items())]
    out += ["", "Registry rule, quoted from tools/params.py:", "",
            "```text"] + rule + ["```"]
